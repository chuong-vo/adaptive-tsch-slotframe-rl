#!/usr/bin/env python3
import argparse
import math
from pathlib import Path
from typing import Dict, Tuple

import matplotlib.pyplot as plt
import pandas as pd

# Map (alpha, beta, delta) -> human-readable label
PROFILE_LABELS: Dict[Tuple[float, float, float], str] = {
    (0.4, 0.3, 0.3): "balanced",
    (0.1, 0.8, 0.1): "delay",
    (0.8, 0.1, 0.1): "energy",
    (0.1, 0.1, 0.8): "reliability",
}

PROFILE_COLORS: Dict[str, str] = {
    "balanced": "tab:blue",
    "delay": "tab:orange",
    "energy": "tab:green",
    "reliability": "tab:red",
}


def profile_name(alpha: float, beta: float, delta: float) -> str:
    key = (round(alpha, 3), round(beta, 3), round(delta, 3))
    return PROFILE_LABELS.get(key, f"({alpha:.2f},{beta:.2f},{delta:.2f})")


def main() -> None:
    parser = argparse.ArgumentParser(description="Plot long-run results with profile highlights.")
    parser.add_argument(
        "csv",
        nargs="?",
        default="output/example.csv",
        help="Path to the CSV file generated by long_run (default: output/example.csv)",
    )
    parser.add_argument(
        "--out",
        default="output/example_summary.png",
        help="Output image path (default: output/example_summary.png)",
    )
    args = parser.parse_args()

    csv_path = Path(args.csv)
    if not csv_path.exists():
        raise SystemExit(f"CSV file not found: {csv_path}")

    df = pd.read_csv(csv_path)
    if df.empty:
        raise SystemExit("CSV is empty")
    if "valid_cycle" in df.columns:
        df = df[df["valid_cycle"].astype(str).str.lower().isin(["true", "1"])].copy()
    if df.empty:
        raise SystemExit("CSV has no valid cycles after filtering")

    df = df.reset_index(drop=True)
    df["cycle"] = df.index
    if "profile" not in df.columns:
        df["profile"] = [profile_name(a, b, d) for a, b, d in zip(df["alpha"], df["beta"], df["delta"])]

    # Determine contiguous runs of the same profile
    segments = []  # (start_idx, end_idx, profile)
    start = 0
    current_profile = df.loc[0, "profile"]
    for idx in range(1, len(df)):
        prof = df.loc[idx, "profile"]
        if prof != current_profile:
            segments.append((start, idx - 1, current_profile))
            start = idx
            current_profile = prof
    segments.append((start, len(df) - 1, current_profile))

    # Prepare figure with subplots
    metrics = [
        ("current_sf_len", "Slotframe size |C|"),
        ("reward", "Immediate reward"),
        ("power_normalized", "Power (normalized)"),
        ("delay_normalized", "Delay (normalized)"),
        ("pdr_mean", "Reliability (PDR)")
    ]

    fig, axes = plt.subplots(len(metrics), 1, figsize=(12, 12), sharex=True)

    for ax, (col, title) in zip(axes, metrics):
        ax.set_ylabel(title)
        for start_idx, end_idx, prof in segments:
            seg = df.loc[start_idx:end_idx]
            color = PROFILE_COLORS.get(prof, "gray")
            ax.plot(seg["cycle"], seg[col], color=color, linewidth=1.5)
            ax.axvspan(seg["cycle"].iloc[0], seg["cycle"].iloc[-1], color=color, alpha=0.06)
        ax.grid(True, linestyle="--", linewidth=0.3, alpha=0.6)

    axes[-1].set_xlabel("Cycle index")

    # Legend using custom handles
    handles = []
    for prof, color in PROFILE_COLORS.items():
        handles.append(plt.Line2D([0], [0], color=color, lw=2, label=prof))
    axes[0].legend(handles=handles, loc="upper right")

    fig.tight_layout()
    out_path = Path(args.out)
    fig.savefig(out_path, dpi=150)
    print(f"Saved plot to {out_path}")


if __name__ == "__main__":
    main()
